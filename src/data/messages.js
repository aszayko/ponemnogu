function pick(messages, random = Math.random) {
  if (!messages?.length) return null;
  return messages[Math.floor(random() * messages.length)];
}

export function getOccasionalCompletionMessage({ force = false, random = Math.random } = {}) {
  return force || random() < 0.23 ? pick(completionMessages, random) : null;
}

export function getStageTransitionMessage(fromStage, toStage, bodyType, random = Math.random) {
  const options = stageMessages[`${fromStage}→${toStage}`];
  if (!options) return null;
  return pick(Array.isArray(options) ? options : options[bodyType] ?? options.female, random);
}

export function getLevelUpMessage(random = Math.random) {
  return pick(levelUpMessages, random);
}

export function getAllDoneMessage(bodyType, random = Math.random) {
  return pick(allDoneMessages[bodyType] ?? allDoneMessages.female, random);
}
